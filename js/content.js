(function applyOverrides() {
  try {
    const raw = localStorage.getItem('sig-content-override');
    if (!raw) return;
    const extra = JSON.parse(raw);
    if (extra.sectors) window.SIG_CONTENT.sectors = extra.sectors;
    if (extra.partners) window.SIG_CONTENT.partners = extra.partners;
    if (extra.clients) window.SIG_CONTENT.clients = extra.clients;
  } catch (e) { /* ignore invalid override */ }
})();

window.SIG_activeSectors = function () {
  return (window.SIG_CONTENT.sectors || []).filter(s => s.active !== false).sort((a, b) => a.order - b.order);
};
window.SIG_activePartners = function () {
  return (window.SIG_CONTENT.partners || []).filter(p => p.active !== false).sort((a, b) => a.order - b.order);
};
window.SIG_activeClients = function () {
  return (window.SIG_CONTENT.clients || []).filter(c => c.active !== false).sort((a, b) => a.order - b.order);
};
